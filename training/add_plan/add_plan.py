"""
Generate and insert synthetic general planning steps (task_tracker) at key
transition points of each trajectory in a base dataset.

This extends the original add_plan behavior (which only inserted a plan at the
start) to also insert updated task_tracker plans at:

  1. Start             — before the first assistant action
  2. After Phase 1     — before the first action that mentions the target file
                         (marks broad exploration as done, localization begins)
  3. After Phase 2     — before the first file-editing action
                         (marks localization as done, editing begins)
  4. After edit        — after the first file-editing action's result
                         (marks editing as done, verification begins)

Each plan is generated by an LLM and cached per (instance_id, checkpoint) in a
local cache directory so interrupted runs can be resumed.

The format follows the task_tracker planning steps found in datasets like
synthetic-code-training/func_localize_claude45_1457i:

  Action (assistant):
    <function=task_tracker>
    <parameter=command>plan</parameter>
    <parameter=task_list>[{"title": "...", "status": "in_progress"}, ...]</parameter>
    <parameter=summary>Plan tasks for ...</parameter>
    <parameter=security_risk>LOW</parameter>
    </function>

  Feedback (user):
    EXECUTION RESULT of [function]:
    Task list has been updated with N item(s).
"""

import argparse
import json
import os
import re
import time
from pathlib import Path

from datasets import Dataset, load_dataset
from openai import OpenAI

# ── Default config ─────────────────────────────────────────────────────────────
DEFAULT_BASE_DATASET = "synthetic-code-training/func_localize_claude47_1467i"
DEFAULT_BASE_URL = "https://inference-api.nvidia.com/v1"
# DEFAULT_MODEL = "nvidia/deepseek-ai/deepseek-v4-flash"
DEFAULT_MODEL = "us/azure/openai/gpt-5.4"
DEFAULT_CACHE_DIR = Path(__file__).parent / "cache"

# ── Regex ──────────────────────────────────────────────────────────────────────
_TASK_LIST_RE = re.compile(r"\[.*\]", re.DOTALL)
_FILE_EDIT_PATTERN = re.compile(
    r"<function=file_editor>\n<parameter=command>(str_replace|insert)</parameter>"
)
_FILE_EDIT_PATH_PATTERN = re.compile(
    r"<function=file_editor>\n<parameter=command>(?:str_replace|insert)</parameter>\n<parameter=path>(.*?)</parameter>",
    re.DOTALL,
)
_EDIT_SUCCESS_PATTERN = re.compile(r"has been edited")
_TASK_TRACKER_PATTERN = re.compile(r"<function=task_tracker[\s>]")


# ── LLM client ────────────────────────────────────────────────────────────────

def make_client(base_url: str, api_key: str) -> OpenAI:
    return OpenAI(base_url=base_url, api_key=api_key)


_SYSTEM_PROMPT = """\
You are generating a task-tracker planning step for an AI coding agent.
The agent is about to start working on a software task.
Your job is to output a single function call that the agent would make at the
very start — before any file exploration — to lay out a structured plan.

Output ONLY the function call, with no surrounding text, no markdown, no
explanation.  Use this exact format:

<function=task_tracker>
<parameter=command>plan</parameter>
<parameter=task_list>[{"title": "...", "status": "in_progress"}, {"title": "...", "status": "todo"}, ...]</parameter>
<parameter=summary>Plan tasks for ...</parameter>
<parameter=security_risk>LOW</parameter>
</function>

Rules:
- The task_list must be valid JSON (double quotes, no trailing commas).
- Include 4-6 tasks.  The first task should have status "in_progress"; the
  rest should have status "todo".
- Tasks should reflect the specific function mentioned in the task description.
- Optionally add a "notes" field to some tasks for helpful context.
- The summary should be a short phrase describing the overall goal.
"""

_USER_PROMPT_TEMPLATE = """\
Here is the task the agent received:

{user_message}

Generate the task_tracker planning step now.
"""

# Checkpoint-specific system prompts for progress-update plans
_CHECKPOINT_SYSTEM_PROMPTS = {
    "after_phase1": """\
You are updating a task-tracker planning step for an AI coding agent.
The agent has just completed broad repository exploration (Phase 1) and has
identified the target file.  It will now begin Phase 2: locating the specific
function within that file.

Output ONLY the function call, with no surrounding text, no markdown, no
explanation.  Use this exact format:

<function=task_tracker>
<parameter=command>plan</parameter>
<parameter=task_list>[{"title": "...", "status": "done"}, {"title": "...", "status": "in_progress"}, ...]</parameter>
<parameter=summary>Transitioning to function localization</parameter>
<parameter=security_risk>LOW</parameter>
</function>

Rules:
- The task_list must be valid JSON (double quotes, no trailing commas).
- Keep the same task titles from the original plan.
- Mark the broad-search / find-file task(s) as "done".
- Mark the localize-function task as "in_progress".
- Mark all remaining tasks as "todo".
- The summary should reflect this phase transition.
""",
    "after_phase2": """\
You are updating a task-tracker planning step for an AI coding agent.
The agent has just completed function localization (Phase 2) and is about to
make the code edit.

Output ONLY the function call, with no surrounding text, no markdown, no
explanation.  Use this exact format:

<function=task_tracker>
<parameter=command>plan</parameter>
<parameter=task_list>[{"title": "...", "status": "done"}, {"title": "...", "status": "in_progress"}, ...]</parameter>
<parameter=summary>Transitioning to editing</parameter>
<parameter=security_risk>LOW</parameter>
</function>

Rules:
- The task_list must be valid JSON (double quotes, no trailing commas).
- Keep the same task titles from the original plan.
- Mark search, find-file, and localize-function tasks as "done".
- Mark the edit / add-docstring task as "in_progress".
- Mark all remaining tasks as "todo".
- The summary should reflect this phase transition.
""",
    "after_edit": """\
You are updating a task-tracker planning step for an AI coding agent.
The agent has just made the code edit and is now verifying that the correct
file was modified.

Output ONLY the function call, with no surrounding text, no markdown, no
explanation.  Use this exact format:

<function=task_tracker>
<parameter=command>plan</parameter>
<parameter=task_list>[{"title": "...", "status": "done"}, {"title": "...", "status": "in_progress"}, ...]</parameter>
<parameter=summary>Verifying the edit</parameter>
<parameter=security_risk>LOW</parameter>
</function>

Rules:
- The task_list must be valid JSON (double quotes, no trailing commas).
- Keep the same task titles from the original plan.
- Mark search, localize, and edit tasks as "done".
- Mark the verify / confirm-edit task as "in_progress" (if it exists);
  otherwise mark the last task as "in_progress".
- Mark any remaining tasks as "todo".
- The summary should reflect this verification phase.
""",
}

_CHECKPOINT_USER_PROMPT_TEMPLATE = """\
Here is the original task the agent received:

{user_message}

Here is the initial plan generated at the start of the trajectory:

{initial_plan}

Generate the updated task_tracker call for the current phase transition.
"""


def generate_plan(
    client: OpenAI,
    model: str,
    user_message: str,
    checkpoint: str = "start",
    initial_plan: str = "",
    max_retries: int = 3,
    retry_delay: float = 5.0,
) -> str | None:
    """
    Call the LLM and return the generated task_tracker function call string,
    or None on failure.

    checkpoint: one of 'start', 'after_phase1', 'after_phase2', 'after_edit'
    initial_plan: the start-plan content (required for non-start checkpoints)
    """
    if checkpoint == "start":
        system_prompt = _SYSTEM_PROMPT
        prompt = _USER_PROMPT_TEMPLATE.format(user_message=user_message.strip())
    else:
        system_prompt = _CHECKPOINT_SYSTEM_PROMPTS[checkpoint]
        prompt = _CHECKPOINT_USER_PROMPT_TEMPLATE.format(
            user_message=user_message.strip(),
            initial_plan=initial_plan.strip(),
        )

    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": prompt},
                ],
                max_tokens=512,
                temperature=0.3,
            )
            content = response.choices[0].message.content or ""
            content = content.strip()
            # Basic validation: must look like a task_tracker call
            if "<function=task_tracker" in content:
                return content
            print(f"  [warn] LLM output didn't contain task_tracker call: {content[:200]}")
        except Exception as exc:
            print(f"  [warn] LLM call failed (attempt {attempt + 1}): {exc}")
            if attempt < max_retries - 1:
                time.sleep(retry_delay)
    return None


# ── Cache helpers ──────────────────────────────────────────────────────────────

def cache_path(cache_dir: Path, instance_id: str, checkpoint: str = "start") -> Path:
    safe_id = re.sub(r"[^\w\-.]", "_", instance_id)
    return cache_dir / f"{safe_id}_{checkpoint}.json"


def load_from_cache(cache_dir: Path, instance_id: str, checkpoint: str = "start") -> str | None:
    p = cache_path(cache_dir, instance_id, checkpoint)
    if p.exists():
        try:
            data = json.loads(p.read_text())
            return data.get("plan_content")
        except Exception:
            return None
    # Backward-compat: old cache used {safe_id}.json for the "start" checkpoint
    if checkpoint == "start":
        safe_id = re.sub(r"[^\w\-.]", "_", instance_id)
        old_path = cache_dir / f"{safe_id}.json"
        if old_path.exists():
            try:
                data = json.loads(old_path.read_text())
                return data.get("plan_content")
            except Exception:
                return None
    return None


def save_to_cache(
    cache_dir: Path, instance_id: str, plan_content: str, checkpoint: str = "start"
) -> None:
    p = cache_path(cache_dir, instance_id, checkpoint)
    p.write_text(
        json.dumps(
            {"instance_id": instance_id, "checkpoint": checkpoint, "plan_content": plan_content}
        )
    )


# ── Plan message builders ──────────────────────────────────────────────────────

def count_tasks(plan_content: str) -> int:
    """Count the number of task items in the task_list."""
    m = _TASK_LIST_RE.search(plan_content)
    if not m:
        return 0
    try:
        tasks = json.loads(m.group(0))
        return len(tasks)
    except Exception:
        # Fall back to counting occurrences of "title"
        return plan_content.count('"title"')


def make_action_message(plan_content: str) -> dict:
    return {"role": "assistant", "content": plan_content}


def make_feedback_message(n_tasks: int) -> dict:
    return {
        "role": "user",
        "content": f"EXECUTION RESULT of [function]:\nTask list has been updated with {n_tasks} item(s).",
    }


# ── Phase boundary detection ────────────────────────────────────────────────────

def _is_task_tracker(msg: dict) -> bool:
    return (
        msg.get("role") == "assistant"
        and _TASK_TRACKER_PATTERN.search(msg.get("content", "")) is not None
    )


def _is_file_editing(msg: dict) -> bool:
    return (
        msg.get("role") == "assistant"
        and _FILE_EDIT_PATTERN.search(msg.get("content", "")) is not None
    )


def _get_file_edit_path(msg: dict) -> str | None:
    m = _FILE_EDIT_PATH_PATTERN.search(msg.get("content", ""))
    return m.group(1).strip() if m else None


def _is_edit_successful(msg: dict | None) -> bool:
    if msg is None:
        return False
    return _EDIT_SUCCESS_PATTERN.search(msg.get("content", "")) is not None


def _get_target_file_basename(messages: list[dict]) -> str | None:
    """Return the basename of the last successfully edited file."""
    target = None
    for i, msg in enumerate(messages):
        if _is_file_editing(msg):
            result_msg = messages[i + 1] if i + 1 < len(messages) else None
            if _is_edit_successful(result_msg):
                path = _get_file_edit_path(msg)
                if path:
                    target = os.path.basename(path)
    return target


def strip_task_tracker_pairs(messages: list[dict]) -> list[dict]:
    """
    Remove all task_tracker action+feedback pairs from a message list.

    Pairs consecutive assistant messages with the following user messages
    (matching the OpenHands batched-tool-call convention), then drops any
    pair whose action is a task_tracker call along with its result message.
    """
    # Build (action_idx, result_idx | None) pairs
    pairs: list[tuple[int, int | None]] = []
    i = 0
    while i < len(messages):
        if messages[i]["role"] == "assistant":
            j = i
            while j < len(messages) and messages[j]["role"] == "assistant":
                j += 1
            n = j - i  # batch size
            results: list[int | None] = []
            k = j
            while k < len(messages) and messages[k]["role"] == "user" and len(results) < n:
                results.append(k)
                k += 1
            results.extend([None] * (n - len(results)))
            for p in range(n):
                pairs.append((i + p, results[p]))
            i = k
        else:
            i += 1

    # Collect indices to drop
    drop: set[int] = set()
    for act_idx, res_idx in pairs:
        if _is_task_tracker(messages[act_idx]):
            drop.add(act_idx)
            if res_idx is not None:
                drop.add(res_idx)

    return [msg for i, msg in enumerate(messages) if i not in drop]


def find_phase_boundaries(messages: list[dict]) -> dict[str, int | None]:
    """
    Find insertion indices for plan checkpoints.

    Returns a dict:
      'start'        — index of first assistant message (insert before it)
      'after_phase1' — index of last non-tt action mentioning target file
                       before first edit (insert before it); None if not found
      'after_phase2' — index of first file-editing action (insert before it);
                       None if not found
      'after_edit'   — index right after the first edit's result user message
                       (insert before it); None if not found
    """
    # Start: before first assistant message
    start_idx: int | None = None
    for i, msg in enumerate(messages):
        if msg.get("role") == "assistant":
            start_idx = i
            break

    # Target file basename (from last successful edit)
    target_basename = _get_target_file_basename(messages)

    # First file-editing action and its result
    first_edit_idx: int | None = None
    first_edit_result_idx: int | None = None
    for i, msg in enumerate(messages):
        if _is_file_editing(msg):
            first_edit_idx = i
            for j in range(i + 1, len(messages)):
                if messages[j].get("role") == "user":
                    first_edit_result_idx = j
                    break
            break

    # Last locating action: last non-tt assistant action before the first edit
    # whose content mentions the target file basename (marks end of Phase 1)
    last_locating_idx: int | None = None
    if target_basename and first_edit_idx is not None:
        for i, msg in enumerate(messages):
            if i >= first_edit_idx:
                break
            if msg.get("role") == "assistant" and not _is_task_tracker(msg):
                if target_basename in msg.get("content", ""):
                    last_locating_idx = i  # keep updating to find the last one

    # After edit: position right after the first edit's result user message
    after_edit_idx: int | None = None
    if first_edit_result_idx is not None:
        after_edit_idx = first_edit_result_idx + 1

    return {
        "start": start_idx,
        "after_phase1": last_locating_idx,
        "after_phase2": first_edit_idx,
        "after_edit": after_edit_idx,
    }


# ── Trajectory insertion ───────────────────────────────────────────────────────

def insert_plans_all_checkpoints(
    messages: list[dict],
    plans: dict[str, str | None],
) -> list[dict]:
    """
    Insert plan action+feedback pairs at each checkpoint.

    plans: dict mapping checkpoint name → plan_content (or None to skip)
    Checkpoints: 'start', 'after_phase1', 'after_phase2', 'after_edit'

    Insertions are done from the highest index to the lowest so that earlier
    indices remain valid after each insertion.

    Returns a new messages list.
    """
    boundaries = find_phase_boundaries(messages)

    # Collect (index, plan_content) pairs for non-None boundaries/plans
    insertions: list[tuple[int, str]] = []
    for checkpoint, idx in boundaries.items():
        plan_content = plans.get(checkpoint)
        if idx is not None and plan_content is not None:
            insertions.append((idx, plan_content))

    if not insertions:
        return list(messages)

    # Deduplicate by index (keep first checkpoint encountered for each index)
    seen: set[int] = set()
    deduped: list[tuple[int, str]] = []
    for idx, content in insertions:
        if idx not in seen:
            seen.add(idx)
            deduped.append((idx, content))

    # Sort descending so we insert from back to front
    deduped.sort(key=lambda x: x[0], reverse=True)

    result = list(messages)
    for idx, plan_content in deduped:
        n_tasks = count_tasks(plan_content)
        action_msg = make_action_message(plan_content)
        feedback_msg = make_feedback_message(n_tasks)
        result = result[:idx] + [action_msg, feedback_msg] + result[idx:]

    return result


# ── Dataset processing ─────────────────────────────────────────────────────────

def derive_hub_repo(base_dataset: str, dataset_size: int) -> str:
    base = base_dataset.split(":")[0]
    base_size = base_dataset.split("_")[-1]
    if base_size[-1] == "i" and base_size[0].isdigit():
        return base.replace(base_size, f"add_plan_{dataset_size}i")
    else:
        return base + f"_add_plan_{dataset_size}i"


CHECKPOINTS = ("start", "after_phase1", "after_phase2", "after_edit")


def process_dataset(
    dataset_name: str,
    api_key: str,
    base_url: str = DEFAULT_BASE_URL,
    model: str = DEFAULT_MODEL,
    cache_dir: Path = DEFAULT_CACHE_DIR,
    output_repo: str | None = None,
    dry_run: bool = False,
    max_retries: int = 3,
):
    cache_dir = Path(cache_dir)
    cache_dir.mkdir(parents=True, exist_ok=True)

    print(f"Loading dataset: {dataset_name}")
    ds = load_dataset(dataset_name, split="train")
    print(f"Loaded {len(ds)} trajectories")

    client = make_client(base_url=base_url, api_key=api_key)

    cached_hits = 0
    llm_calls = 0
    llm_failures = 0
    processed_rows = []

    for idx, row in enumerate(ds):
        iid = row.get("instance_id", f"row_{idx}")
        messages = strip_task_tracker_pairs(row["messages"])

        # Find first user message content (for LLM prompts)
        user_msg_content = ""
        for m in messages:
            if m.get("role") == "user":
                user_msg_content = m.get("content", "")
                break

        # Find phase boundaries for this trajectory
        boundaries = find_phase_boundaries(messages)

        # Generate/load plans for each checkpoint in order.
        # 'start' must come first so subsequent checkpoints can reference it.
        plans: dict[str, str | None] = {}

        for checkpoint in CHECKPOINTS:
            # Skip checkpoints whose boundary doesn't exist in this trajectory
            if boundaries.get(checkpoint) is None:
                plans[checkpoint] = None
                continue

            cached = load_from_cache(cache_dir, iid, checkpoint)
            if cached is not None:
                cached_hits += 1
                plans[checkpoint] = cached
            else:
                llm_calls += 1
                if idx % 50 == 0:
                    print(
                        f"  [{idx}/{len(ds)}] Generating plan for {iid} ({checkpoint}) ..."
                    )
                plan_content = generate_plan(
                    client=client,
                    model=model,
                    user_message=user_msg_content,
                    checkpoint=checkpoint,
                    # Pass the start plan so update prompts can reference it
                    initial_plan=plans.get("start") or "",
                    max_retries=max_retries,
                )
                if plan_content is None:
                    llm_failures += 1
                    print(f"  [warn] Failed to generate {checkpoint} plan for {iid}")
                else:
                    save_to_cache(cache_dir, iid, plan_content, checkpoint)
                plans[checkpoint] = plan_content

        # If the start plan failed, keep the original trajectory unchanged
        if plans.get("start") is None:
            print(f"  [skip] No start plan for {iid}")
            processed_rows.append(row)
            continue

        new_messages = insert_plans_all_checkpoints(messages, plans)
        processed_rows.append({**row, "messages": new_messages})

    kept = len(processed_rows)
    hub_repo = output_repo or derive_hub_repo(dataset_name, dataset_size=kept)

    print("\nResults:")
    print(f"  Total trajectories:    {len(ds)}")
    print(f"  Kept:                  {kept}")
    print(f"  Cache hits:            {cached_hits}")
    print(f"  LLM calls:             {llm_calls}")
    print(f"  LLM failures (warned): {llm_failures}")
    print(f"  Output repo:           {hub_repo}")

    if dry_run:
        print("\n[dry-run] Skipping push to HuggingFace Hub.")
        return kept

    processed_ds = Dataset.from_list(processed_rows)
    print(f"\nPushing to Hub: {hub_repo}")
    processed_ds.push_to_hub(hub_repo, split="train")
    print("Done.")

    return kept


# ── Entry point ────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Insert synthetic LLM-generated task_tracker planning steps "
                    "at key phase transitions in each trajectory of a base dataset."
    )
    parser.add_argument(
        "--dataset",
        default=DEFAULT_BASE_DATASET,
        help="HuggingFace dataset name for the base trajectories "
             f"(default: {DEFAULT_BASE_DATASET})",
    )
    parser.add_argument(
        "--api-key",
        default=os.environ.get("NVIDIA_API_KEY", ""),
        help="API key for the LLM endpoint (default: $NVIDIA_API_KEY)",
    )
    parser.add_argument(
        "--base-url",
        default=DEFAULT_BASE_URL,
        help=f"Base URL for the LLM endpoint (default: {DEFAULT_BASE_URL})",
    )
    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
        help=f"Model name (default: {DEFAULT_MODEL})",
    )
    parser.add_argument(
        "--cache-dir",
        default=str(DEFAULT_CACHE_DIR),
        help=f"Directory to cache generated plans (default: {DEFAULT_CACHE_DIR})",
    )
    parser.add_argument(
        "--output-repo",
        default=None,
        help="HuggingFace repo to push results to "
             "(default: {dataset}_add_plan)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Process and report stats without pushing to HuggingFace Hub",
    )
    parser.add_argument(
        "--max-retries",
        type=int,
        default=3,
        help="Max retries per LLM call on failure (default: 3)",
    )
    args = parser.parse_args()

    if not args.api_key:
        parser.error(
            "No API key provided. Set NVIDIA_API_KEY or pass --api-key."
        )

    process_dataset(
        dataset_name=args.dataset,
        api_key=args.api_key,
        base_url=args.base_url,
        model=args.model,
        cache_dir=Path(args.cache_dir),
        output_repo=args.output_repo,
        dry_run=args.dry_run,
        max_retries=args.max_retries,
    )


if __name__ == "__main__":
    main()
